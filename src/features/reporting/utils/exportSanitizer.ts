/**
 * BAOMS Phase 10: Export Sanitization & Spreadsheet Formula Injection Defense
 * Babawatoto Organization Management System
 * 
 * Protects against CSV / Spreadsheet Formula Injection (CWE-1236)
 * and masks confidential/sensitive fields during data export.
 */

import { ReportDataSet, ExportReportOptions } from '../types/reporting';

const FORMULA_TRIGGER_CHARS = ['=', '+', '-', '@', '\t', '\r'];

const CONFIDENTIAL_FIELD_PATTERNS = [
  /password/i,
  /secret/i,
  /token/i,
  /hash/i,
  /emergency.*phone/i,
  /pin/i,
  /mfa/i,
  /private/i,
];

/**
 * Checks whether a column key represents confidential or restricted data
 */
export function isConfidentialField(fieldKey: string): boolean {
  return CONFIDENTIAL_FIELD_PATTERNS.some((pattern) => pattern.test(fieldKey));
}

/**
 * Escapes a cell value to prevent CSV Formula Injection.
 * Cells starting with '=', '+', '-', '@', '\t', or '\r' are prepended with a single quote.
 */
export function sanitizeSpreadsheetValue(val: unknown): string {
  if (val === null || val === undefined) {
    return '';
  }

  const rawStr = String(val);

  // Guard against CSV Formula Injection:
  // Check if raw or trimmed starts with any formula trigger character (=, +, -, @, \t, \r)
  let str = rawStr;
  const trimmed = rawStr.trimStart();
  if (rawStr.length > 0 && FORMULA_TRIGGER_CHARS.includes(rawStr.charAt(0))) {
    str = `'${rawStr}`;
  } else if (trimmed.length > 0 && FORMULA_TRIGGER_CHARS.includes(trimmed.charAt(0))) {
    str = `'${trimmed}`;
  } else {
    str = rawStr.trim();
  }

  // Escape interior double-quotes by doubling them (RFC 4180 standard)
  const escaped = str.replace(/"/g, '""');

  // Wrap in double quotes if it contains commas, quotes, newlines, or leading single quote
  if (
    escaped.includes(',') ||
    escaped.includes('"') ||
    escaped.includes('\n') ||
    escaped.includes('\r') ||
    escaped.startsWith("'")
  ) {
    return `"${escaped}"`;
  }

  return escaped;
}

/**
 * Generates an RFC 4180-compliant CSV string with UTF-8 BOM, metadata header,
 * formula injection prevention, and confidential field masking.
 */
export function generateCsvContent(
  report: ReportDataSet,
  options: ExportReportOptions = {}
): string {
  const { maskConfidential = true, includeBOM = true } = options;

  // Filter out confidential columns if masking is active
  const exportColumns = maskConfidential
    ? report.columns.filter((col) => !isConfidentialField(col.key))
    : report.columns;

  const lines: string[] = [];

  // Metadata comments header
  lines.push(`# Babawatoto Organization Management System (BAOMS) - Official Report`);
  lines.push(`# Title: ${sanitizeSpreadsheetValue(report.metadata.reportTitle).replace(/^"|"$/g, '')}`);
  lines.push(`# Category: ${report.metadata.reportCategory.toUpperCase()}`);
  lines.push(`# Generated At: ${report.metadata.generatedAt}`);
  lines.push(`# Generated By: ${sanitizeSpreadsheetValue(report.metadata.generatedByName).replace(/^"|"$/g, '')}`);
  lines.push(`# Date Range: ${report.metadata.dateRangeLabel}`);
  lines.push(`# Total Records: ${report.rows.length}`);
  lines.push('');

  // Column Header row
  const headerRow = exportColumns
    .map((col) => sanitizeSpreadsheetValue(col.header))
    .join(',');
  lines.push(headerRow);

  // Data rows
  for (const row of report.rows) {
    const rowValues = exportColumns.map((col) => {
      const cellValue = row[col.key];
      return sanitizeSpreadsheetValue(cellValue);
    });
    lines.push(rowValues.join(','));
  }

  const csvBody = lines.join('\r\n');
  // Prepend UTF-8 BOM (\uFEFF) to guarantee Excel correctly parses UTF-8 Swahili and symbols
  return includeBOM ? `\uFEFF${csvBody}` : csvBody;
}

/**
 * Initiates browser file download for the CSV report
 */
export function downloadReportAsCsv(
  report: ReportDataSet,
  customFilename?: string
): void {
  try {
    const csvData = generateCsvContent(report);
    const dateStamp = new Date().toISOString().split('T')[0];
    const safeTitle = report.metadata.reportTitle
      .toLowerCase()
      .replace(/[^a-z0-9_-]/g, '_');
    const filename = customFilename || `BAOMS_${safeTitle}_${dateStamp}.csv`;

    const blob = new Blob([csvData], { type: 'text/csv;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.setAttribute('download', filename);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  } catch (err: unknown) {
    const message = err instanceof Error ? err.message : 'Unknown export failure';
    throw new Error(`Export generation failed: ${message}`);
  }
}
