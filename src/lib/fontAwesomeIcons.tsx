export const FontAwesomeIcon = forwardRef<SVGSVGElement, FontAwesomeIconProps>((props, ref) => {
  const { icon, size = 24, color = 'currentColor', className = '', style, children, ...rest } = props;
  
  let faName = 'circle-question';
  if (typeof icon === 'string') {
    const clean = icon.replace(/^fa-(solid|regular|brands)\s+/, '').replace(/^fa-/, '');
    faName = FA_ICON_MAP[icon] || FA_ICON_MAP[clean] || (FA_GLYPHS[clean] ? clean : (FA_GLYPHS[icon] ? icon : 'circle-question'));
  }

  const glyph = FA_GLYPHS[faName] || FA_GLYPHS['circle-question'] || { viewBox: '0 0 512 512', d: '' };

  return (
    <svg
      ref={ref}
      xmlns="http://www.w3.org/2000/svg"
      viewBox={glyph.viewBox}
      width={size}
      height={size}
      fill={color}
      className={`svg-inline--fa fa-${faName} ${className}`.trim()}
      role="img"
      aria-hidden="true"
      style={style}
      {...rest}
    >
      <path fill="currentColor" d={glyph.d} />
      {children}
    </svg>
  );
});
FontAwesomeIcon.displayName = 'FontAwesomeIcon';

function createIcon(lucideName: string, faName: string): LucideIcon {
  const glyph = FA_GLYPHS[faName] || { viewBox: '0 0 512 512', d: '' };
  const Component = forwardRef<SVGSVGElement, IconProps>((props, ref) => {
    const { size = 24, color = 'currentColor', className = '', style, children, ...rest } = props;
    return (
      <svg
        ref={ref}
        xmlns="http://www.w3.org/2000/svg"
        viewBox={glyph.viewBox}
        width={size}
        height={size}
        fill={color}
        className={`svg-inline--fa fa-${faName} ${className}`.trim()}
        role="img"
        aria-hidden="true"
        style={style}
        {...rest}
      >
        <path fill="currentColor" d={glyph.d} />
        {children}
      </svg>
    );
  });
  Component.displayName = lucideName;
  return Component;
}

